function arrayAnchor(content, name) {
  const open = new RegExp(`^\\s*${name}\\s*=\\s*\\[`);
  for (let i = 0; i < content.length; i += 1) {
    if (open.test(content[i])) return i;
  }
  return -1;
}

function bodyEnd(lines) {
  const content = lines.map(contentOf);
  let last = -1;
  for (let i = 0; i < content.length; i += 1) {
    const line = content[i];
    if (line.trim() === '' || line.startsWith('#') || line.startsWith('[')) continue;
    last = i;
  }
  return last;
}

function regionSpan(content, key, suffix) {
  const name = `${SENTINEL_PREFIX} ${key}${suffix}`;
  const exact = (line, tail) => line === `${name}${tail}`;
  const begin = content.findIndex((line) => exact(line, ' (generated; do not edit by hand)'));
  if (begin !== -1) {
    const end = content.findIndex((line, at) => at > begin && exact(line, ' end'));
    if (end === -1) throw new Error(`host manifest: end sentinel not found: ${name} end`);
    return { from: begin, to: end };
  }
  const absent = content.findIndex((line) => exact(line, ' absent'));
  if (absent !== -1) return { from: absent, to: absent };
  return null;
}

function regionSpans(content, key, suffix) {
  const name = `${SENTINEL_PREFIX} ${key}${suffix}`;
  const exact = (line, tail) => line === `${name}${tail}`;
  const OPEN = ' (generated; do not edit by hand)';
  const spans = [];
  let cursor = 0;
  while (cursor < content.length) {
    const begin = content.findIndex((line, at) => at >= cursor && exact(line, OPEN));
    const absent = content.findIndex((line, at) => at >= cursor && exact(line, ' absent'));
    if (begin === -1 && absent === -1) break;
    if (absent !== -1 && (begin === -1 || absent < begin)) {
      spans.push({ from: absent, to: absent });
      cursor = absent + 1;
      continue;
    }
    const end = content.findIndex((line, at) => at > begin && exact(line, ' end'));
    if (end === -1) throw new Error(`host manifest: end sentinel not found: ${name} end`);
    spans.push({ from: begin, to: end });
    cursor = end + 1;
  }
  return spans;
}

function sectionBlock(section) {
  const { marker, body } = section;
  return body === null
    ? [marker.absent]
    : [
      marker.begin,
      ...body,
      ...Array(section.padding).fill(''),
      marker.end,
    ];
}

function dropRegion(lines, section) {
  const content = lines.map(contentOf);
  const spans = regionSpans(content, section.key, section.suffix);
  if (spans.length === 0) return lines;
  const kept = [];
  let cursor = 0;
  for (const span of spans) {
    kept.push(...lines.slice(cursor, span.from));
    cursor = span.to + 1;
  }
  kept.push(...lines.slice(cursor));
  return kept;
}

function writeRegion(lines, terminator, section) {
  const content = lines.map(contentOf);
  const block = sectionBlock(section).map((line) => line + terminator);
  const spans = regionSpans(content, section.key, section.suffix);
  if (spans.length > 0) {
    const first = spans[0];
    const kept = lines.slice(0, first.from);
    let cursor = first.to + 1;
    for (const span of spans.slice(1)) {
      kept.push(...lines.slice(cursor, span.from));
      cursor = span.to + 1;
    }
    kept.push(...lines.slice(cursor));
    return [...kept.slice(0, first.from), ...block, ...kept.slice(first.from)];
  }
  const written = block;
  if (section.array !== null && section.array !== undefined) {
    const at = arrayAnchor(content, section.array);
    if (at !== -1) return [...lines.slice(0, at + 1), ...written, ...lines.slice(at + 1)];
  }
  let header = -1;
  if (section.table !== null) {
    header = content.findIndex((line) => line.trim() === `[${section.table}]`);
    if (header === -1) {
      throw new Error(`host manifest: ${section.marker.begin} stands nowhere and its table [${section.table}] is not in the file`);
    }
    const last = bodyEnd(lines.slice(header));
    const at = last === -1 ? header : header + last;
    return [...lines.slice(0, at + 1), terminator, ...written, ...lines.slice(at + 1)];
  }
  const last = bodyEnd(lines);
  const at = last === -1 ? content.length - 1 : last;
  return [...lines.slice(0, at + 1), terminator, ...written, ...lines.slice(at + 1)];
}



function staleSnapshotEntries(snapshotText, sourceName, treeRoot) {
  const stale = [];
  const arrays = snapshotDeclaresWorkspaceText(snapshotText)
    ? [
      ['members', readStringArray(snapshotText, 'members', sourceName)],
      ['exclude', readStringArray(snapshotText, 'exclude', sourceName)],
    ]
    : [];
  for (const [array, entries] of arrays) {
    for (const entry of entries) {
      const target = join(treeRoot, ...entry.split('/'));
      let present = false;
      try {
        present = statSync(target).isDirectory();
      } catch {
        present = false;
      }
      if (!present) stale.push({ array, entry });
    }
  }
  return stale;
}

function pruneSnapshot(snapshotText, stale, sourceName) {
  const gone = new Set(stale.map(({ array, entry }) => `${array}\u0000${entry}`));
  const lines = splitLines(snapshotText);
  const out = [];
  let array = null;
  for (const line of lines) {
    const opened = line.match(/^\s*(members|exclude)\s*=\s*\[/);
    if (opened) {
      array = opened[1];
      out.push(line);
      continue;
    }
    if (array !== null && /^\s*\]/.test(line)) {
      array = null;
      out.push(line);
      continue;
    }
    if (array !== null) {
      const quoted = contentOf(line).trim().match(/^"([^"]+)"\s*,?$/);
      if (quoted && gone.has(`${array}\u0000${quoted[1]}`)) continue;
    }
    out.push(line);
  }
  const text = out.join('\n');
  if (readStringArray(text, 'members', sourceName).length === 0) {
    throw new Error(
      `${sourceName}: pruning every stale entry would leave the members array empty. That describes a tree with no crates at all`,
    );
  }
  return text;
}

